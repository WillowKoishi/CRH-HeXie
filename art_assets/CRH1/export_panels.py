#!/usr/bin/env python3
"""Export CRH1A panels to the shared NeoForge carriage-part pipeline (stdlib only)."""

import argparse
import base64
import json
from pathlib import Path
import struct
import sys
import zlib

# Exporting artwork should not leave Python cache artifacts in the source tree.
sys.dont_write_bytecode = True
from crh1a_bogey.export_bogeys import entries, normal, number, world_vertices

SOURCE = Path(__file__).resolve().parent
RESOURCES = SOURCE.parents[1] / "src/generated/resources"
NAME = "crh1a_panel_small_window"
PANELS = {NAME: (7, 58), "crh1a_panel_nowindow": (2, 16)}


def json_bytes(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def split_texture(data):
    """Keep authored RGBA pixels; opaque body and fractional-alpha glass render separately."""
    assert data[:8] == b"\x89PNG\r\n\x1a\n"
    offset, compressed = 8, bytearray()
    while offset < len(data):
        length = struct.unpack_from(">I", data, offset)[0]
        kind, payload = data[offset + 4:offset + 8], data[offset + 8:offset + 8 + length]
        if kind == b"IHDR":
            header = payload
        elif kind == b"IDAT":
            compressed.extend(payload)
        offset += length + 12
    width, height, depth, color, compression, filtering, interlace = struct.unpack(">IIBBBBB", header)
    if (depth, color, compression, filtering, interlace) != (8, 6, 0, 0, 0):
        raise ValueError("Expected non-interlaced RGBA8 source texture")
    raw = zlib.decompress(compressed)
    stride, previous, pixels = width * 4, bytearray(width * 4), bytearray()
    for row in range(height):
        start = row * (stride + 1)
        mode, scan = raw[start], bytearray(raw[start + 1:start + 1 + stride])
        for i in range(stride):
            left, above = scan[i - 4] if i >= 4 else 0, previous[i]
            corner = previous[i - 4] if i >= 4 else 0
            if mode == 4:
                prediction = left + above - corner
                distances = [abs(prediction - v) for v in (left, above, corner)]
                predictor = (left, above, corner)[distances.index(min(distances))]
            elif mode in (0, 1, 2, 3):
                predictor = (0, left, above, (left + above) // 2)[mode]
            else:
                raise ValueError("Unknown PNG filter")
            scan[i] = (scan[i] + predictor) & 255
        pixels.extend(scan)
        previous = scan

    def chunk(kind, payload):
        return struct.pack(">I", len(payload)) + kind + payload + struct.pack(">I", zlib.crc32(kind + payload))

    result = {}
    for layer in ("body", "glass"):
        if layer == "glass" and not any(0 < alpha < 255 for alpha in pixels[3::4]):
            continue
        output = bytearray(pixels)
        for i in range(3, len(output), 4):
            keep = pixels[i] == 255 if layer == "body" else 0 < pixels[i] < 255
            if not keep:
                output[i] = 0
        rows = b"".join(b"\0" + output[y * stride:(y + 1) * stride] for y in range(height))
        result[layer] = data[:8] + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b"")
    return result


def export_obj(model, right=False, name=NAME):
    lines = ["# CRH1A artwork: GPL-3.0-only; original attribution in the .bbmodel source.",
             "# Generated by art_assets/CRH1/export_panels.py; reference cube excluded.",
             f"mtllib {name}.mtl"]
    vertex_count = uv_count = normal_count = face_count = mesh_count = 0
    points = []
    for element, parents in entries(model):
        # The top-level reference cube is an editing aid, never part of the game model.
        if element["name"] == "参考方块" or not parents:
            continue
        if not all(node.get("export", True) and node.get("visibility", True) for node in [element, *parents]):
            continue
        if element["type"] != "mesh":
            raise ValueError("Expected authored panel meshes")
        vertices = {}
        for key, (x, y, z) in world_vertices(element, parents).items():
            # Same reference-block frame as CRH2A: +Z runs along the panel, -X faces out.
            point = (z + .5, y, -x - .5)
            vertices[key] = (1 - point[0], point[1], point[2]) if right else point
        points.extend(vertices.values())
        indices = {key: vertex_count + i + 1 for i, key in enumerate(vertices)}
        lines.extend(["o " + element["uuid"], "usemtl t0"])
        lines.extend("v " + " ".join(map(number, vertex)) for vertex in vertices.values())
        vertex_count += len(vertices)
        mesh_count += 1
        for face in element["faces"].values():
            if face.get("texture") is None or len(face["vertices"]) < 3:
                continue
            keys = list(reversed(face["vertices"])) if right else face["vertices"]
            if len(keys) > 4:
                raise ValueError("Triangulate source polygons with more than four corners")
            texture = model["textures"][face["texture"]]
            for key in keys:
                u, v = face["uv"][key]
                lines.append(f"vt {number(u / texture['uv_width'])} {number(1 - v / texture['uv_height'])}")
            lines.append("vn " + " ".join(map(number, normal([vertices[key] for key in keys]))))
            normal_count += 1
            lines.append("f " + " ".join(f"{indices[key]}/{uv_count + i + 1}/{normal_count}" for i, key in enumerate(keys)))
            uv_count += len(keys)
            face_count += 1
    bounds = [min(p[i] for p in points) for i in range(3)] + [max(p[i] for p in points) for i in range(3)]
    if (mesh_count, face_count) != PANELS[name]:
        raise ValueError(f"Unexpected panel geometry: {mesh_count} meshes, {face_count} faces")
    return ("\n".join(lines) + "\n").encode("utf-8"), bounds


def outputs(name=NAME):
    model = json.loads((SOURCE / (name + ".bbmodel")).read_text(encoding="utf-8-sig"))
    model_id = f"hexie:block/crh1a/parts/{name}"
    texture_id = model_id
    result = {}
    model_dir = Path("assets/hexie/models/block/crh1a/parts")
    texture_dir = Path("assets/hexie/textures/block/crh1a/parts")
    data = base64.b64decode(model["textures"][0]["source"].split(",", 1)[1])
    result[texture_dir / (name + ".png")] = data
    layers = split_texture(data)
    for layer, pixels in layers.items():
        result[texture_dir / f"{name}_{layer}.png"] = pixels
    result[model_dir / f"{name}.mtl"] = b"newmtl t0\nmap_Kd #t0\nKd 1 1 1\nd 1\n"
    for right in (False, True):
        suffix = "_right" if right else ""
        obj, bounds = export_obj(model, right, name)
        result[model_dir / f"{name}{suffix}.obj"] = obj
        for layer in layers:
            result[model_dir / f"{name}{suffix}_{layer}.json"] = json_bytes({
                "parent": "minecraft:block/block", "loader": "neoforge:obj", "ambientocclusion": False,
                "shade_quads": False, "emissive_ambient": False, "automatic_culling": False, "flip_v": True,
                "model": f"hexie:models/block/crh1a/parts/{name}{suffix}.obj",
                "render_type": "minecraft:cutout" if layer == "body" else "minecraft:translucent",
                "textures": {"particle": texture_id, "t0": f"{texture_id}_{layer}"}})
        result[model_dir / f"{name}{suffix}.json"] = json_bytes({
            "parent": "minecraft:block/block", "loader": "neoforge:composite", "ambientocclusion": False,
            "textures": {"particle": texture_id},
            "children": {layer: {"parent": f"{model_id}{suffix}_{layer}"} for layer in layers},
            "item_render_order": list(layers)})
        if not right:
            result[Path(f"data/hexie/crh2a_parts/{name}.json")] = json_bytes({
                "mount": [0, 0, 1], "side": True, "remote": False, "check_side": False,
                "bounds": bounds, "boxes": [bounds]})
    # Member cells are invisible, but breaking/hitting them still samples their model's particle.
    result[model_dir / f"{name}_member.json"] = json_bytes({
        "parent": "minecraft:block/block", "textures": {"particle": texture_id}, "elements": []})
    variants = {}
    for facing, rotation in (("north", 0), ("east", 90), ("south", 180), ("west", 270)):
        for part in range(16):
            for hinge in ("left", "right"):
                parent = model_id + ("_right" if hinge == "right" else "") if part == 0 else model_id + "_member"
                variants[f"facing={facing},part={part},hinge={hinge}"] = {"model": parent, "y": rotation}
    result[Path(f"assets/hexie/blockstates/{name}.json")] = json_bytes({"variants": variants})
    result[Path(f"assets/hexie/models/item/{name}.json")] = json_bytes({
        "parent": model_id, "display": {
            "gui": {"rotation": [25, 135, 0], "scale": [.35, .35, .35]},
            "ground": {"scale": [.25, .25, .25]}, "fixed": {"scale": [.4, .4, .4]}}})
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated resources without writing")
    args = parser.parse_args()
    generated = {}
    for name in PANELS:
        generated.update(outputs(name))
    stale = []
    for relative, payload in generated.items():
        target = RESOURCES / relative
        if args.check:
            if not target.exists() or target.read_bytes() != payload:
                stale.append(str(relative))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(payload)
    if stale:
        raise SystemExit("Stale resources:\n" + "\n".join(stale))
    print(f"{'Verified' if args.check else 'Exported'} {len(generated)} resources for {len(PANELS)} panels; reference cubes excluded.")


if __name__ == "__main__":
    main()
