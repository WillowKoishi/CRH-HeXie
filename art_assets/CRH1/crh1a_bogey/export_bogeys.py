#!/usr/bin/env python3
"""Export the authored CRH1A bogeys to NeoForge OBJ partials (Python 3, stdlib only)."""

import argparse
import base64
from collections import Counter, defaultdict
import json
import math
from pathlib import Path

SOURCE = Path(__file__).resolve().parent
ROOT = SOURCE.parents[2]
RESOURCES = ROOT / "src/generated/resources"
MODELS = RESOURCES / "assets/hexie/models/block/bogey"
TEXTURES = RESOURCES / "assets/hexie/textures/block/bogey"
# These visible, fully textured meshes were disabled together with the frame's wheel references.
# Only the standalone trailer wheel's three discs are restored, never the duplicate wheel groups.
TRAILER_DISCS = {
    "d32cf124-c366-587a-a889-0bd134e4586c",
    "2a0ef029-0bac-9d08-a926-8a1fb62ba281",
    "d783e89b-0b63-2859-1ade-cefde8fa59a8",
}


def rotate(vector, rotation):
    """Bake mesh/group rotations in Blockbench's order, verified against its supplied OBJ."""
    x, y, z = vector
    for axis in "zyx":
        angle = math.radians(rotation["xyz".index(axis)])
        c, s = math.cos(angle), math.sin(angle)
        if axis == "x":
            y, z = y * c - z * s, y * s + z * c
        elif axis == "y":
            x, z = x * c + z * s, -x * s + z * c
        else:
            x, y = x * c - y * s, x * s + y * c
    return x, y, z


def world_vertices(element, parents):
    result = {}
    for key, vertex in element["vertices"].items():
        point = tuple(a + b for a, b in zip(rotate(vertex, element["rotation"]), element["origin"]))
        for group in reversed(parents):
            origin = group["origin"]
            relative = tuple(a - b for a, b in zip(point, origin))
            point = tuple(a + b for a, b in zip(rotate(relative, group["rotation"]), origin))
        result[key] = tuple(value / 16 for value in point)
    return result


def entries(model):
    groups = {group["uuid"]: group for group in model.get("groups", [])}
    elements = {element["uuid"]: element for element in model["elements"]}

    def walk(nodes, parents):
        for node in nodes:
            if isinstance(node, dict):
                yield from walk(node.get("children", []), parents + [groups.get(node["uuid"], node)])
            else:
                yield elements[node], parents

    return list(walk(model["outliner"], []))


def part_for(element, parents):
    names = [group["name"] for group in parents]
    name = element["name"]
    side = "left" if element["origin"][0] < 0 else "right"
    if any(n.startswith("一系悬挂") for n in names):
        return "primary_suspension"
    if any(n.startswith("牵引电机") for n in names):
        return "motors"
    if any(n.startswith(("动车刹车", "拖车刹车")) for n in names) or name == "动车刹车构架":
        return "brakes"
    if any(n.startswith("空气弹簧") for n in names) and element["origin"][1] == 5.5:
        return "air_spring_" + side
    if any(n.startswith("抗蛇行减震器") for n in names):
        return "yaw_damper_" + side + ("_shaft" if name == "内活塞" else "_sleeve")
    if name == "抗蛇行减震器座子（枕梁端）":
        return "yaw_damper_" + side + "_upper_mount"
    if name in ("枕梁", "牵引拉杆座子（枕梁端）"):
        return "bolster"
    if name == "牵引拉杆":
        return "traction_rod"
    if name == "垂向减震器":
        return "vertical_damper_" + side
    if "抗侧滚扭杆机构" in names:
        return "anti_roll_link_" + side if element["origin"][1] == .9 else "anti_roll_bar"
    return "frame"


def number(value):
    return f"{0 if abs(value) < 1e-10 else value:.9f}".rstrip("0").rstrip(".")


def normal(points):
    # Newell's method preserves the original face winding, including mesh quads.
    n = [0., 0., 0.]
    for a, b in zip(points, points[1:] + points[:1]):
        n[0] += (a[1] - b[1]) * (a[2] + b[2])
        n[1] += (a[2] - b[2]) * (a[0] + b[0])
        n[2] += (a[0] - b[0]) * (a[1] + b[1])
    length = math.sqrt(sum(v * v for v in n))
    if length < 1e-12:
        raise ValueError("Degenerate authored face")
    return tuple(v / length for v in n)


def export_obj(part_entries, model):
    lines = ["# CRH1A artwork: GPL-3.0-only; original attribution in the .bbmodel sources.",
             "# Generated by art_assets/CRH1/crh1a_bogey/export_bogeys.py; block units.", "mtllib parts.mtl"]
    vertex_count = uv_count = normal_count = face_count = 0
    for element, parents in part_entries:
        vertices = world_vertices(element, parents)
        indices = {key: vertex_count + i + 1 for i, key in enumerate(vertices)}
        lines.append("o " + element["uuid"])
        lines.extend("v " + " ".join(map(number, vertex)) for vertex in vertices.values())
        vertex_count += len(vertices)
        for face in element["faces"].values():
            keys = face["vertices"]
            if len(keys) < 3 or face.get("texture") is None:
                continue
            if len(keys) > 4:
                raise ValueError("Unexpected polygon; triangulate in the source first")
            texture = model["textures"][face["texture"]]
            material = {"crh1a_bogie_frame_motor.png": "frame", "crh1a_bogie_wheel.png": "wheel",
                        "crh1a_bogie_wheel_trailer.png": "wheel"}.get(texture["name"])
            if material is None:
                raise ValueError("Reference texture leaked into bogey: " + texture["name"])
            lines.append("usemtl " + material)
            for key in keys:
                u, v = face["uv"][key]
                lines.append("vt " + number(u / texture["uv_width"]) + " " + number(1 - v / texture["uv_height"]))
            lines.append("vn " + " ".join(map(number, normal([vertices[key] for key in keys]))))
            normal_count += 1
            lines.append("f " + " ".join(f"{indices[key]}/{uv_count + i + 1}/{normal_count}" for i, key in enumerate(keys)))
            uv_count += len(keys)
            face_count += 1
    return ("\n".join(lines) + "\n").encode("utf-8"), face_count


def json_bytes(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def outputs():
    result = {}
    for variant, frame_source, wheel_source in [
        ("motor", "crh1_bogie_frame_motorl", "crh1_bogie_wheel"),
        ("trailer", "crh1_bogie_frame_trailer", "crh1_bogie_wheel_trailer"),
    ]:
        directory = "crh1a_" + variant
        frame = json.loads((SOURCE / (frame_source + ".bbmodel")).read_text(encoding="utf-8-sig"))
        wheel = json.loads((SOURCE / (wheel_source + ".bbmodel")).read_text(encoding="utf-8-sig"))
        parts = defaultdict(list)
        excluded = Counter()
        for element, parents in entries(frame):
            reference = next((g["name"] for g in parents if g["name"] in ("rails", "wheel", "wheel2")), None)
            if reference:
                excluded[reference] += 1
                continue
            if not element.get("export", True) or not all(g.get("export", True) for g in parents):
                raise ValueError("Unexpected disabled non-reference mesh: " + element["uuid"])
            parts[part_for(element, parents)].append((element, parents))
        wheel_entries = []
        restored = set()
        for element, parents in entries(wheel):
            restore = variant == "trailer" and element["uuid"] in TRAILER_DISCS
            if element.get("export", True) or restore:
                wheel_entries.append((element, parents))
            if restore:
                restored.add(element["uuid"])
        if variant == "trailer" and restored != TRAILER_DISCS:
            raise ValueError("Trailer brake disc sources changed; review the extraction")
        parts["wheel"] = wheel_entries
        expected = {"frame", "wheel", "primary_suspension", "brakes", "bolster", "anti_roll_bar", "traction_rod"}
        for side in ("left", "right"):
            expected.update({"air_spring_" + side, "vertical_damper_" + side, "anti_roll_link_" + side})
            expected.update("yaw_damper_" + side + suffix for suffix in ("_shaft", "_sleeve", "_upper_mount"))
        if variant == "motor":
            expected.add("motors")
        if set(parts) != expected:
            raise ValueError("Unexpected part set: " + str(set(parts) ^ expected))
        counts = {}
        for part, part_entries in sorted(parts.items()):
            source = wheel if part == "wheel" else frame
            obj, face_count = export_obj(part_entries, source)
            result[MODELS / directory / (part + ".obj")] = obj
            result[MODELS / directory / (part + ".json")] = json_bytes({
                "parent": "minecraft:block/block", "loader": "neoforge:obj", "flip_v": True,
                "automatic_culling": False, "model": f"hexie:models/block/bogey/{directory}/{part}.obj",
                "textures": {"particle": f"hexie:block/bogey/{directory}/frame"},
            })
            counts[part] = {"meshes": len(part_entries), "faces": face_count}
        result[MODELS / directory / "parts.mtl"] = (
            f"# CRH1A original textures; GPL-3.0-only.\nnewmtl frame\nmap_Kd hexie:block/bogey/{directory}/frame\n"
            f"newmtl wheel\nmap_Kd hexie:block/bogey/{directory}/wheel\n"
        ).encode("utf-8")
        texture = wheel["textures"][0]
        result[TEXTURES / directory / "wheel.png"] = base64.b64decode(texture["source"].split(",", 1)[1])
        summary = {"source_frame": frame_source + ".bbmodel", "source_wheel": wheel_source + ".bbmodel",
                   "units_per_block": 16, "axle_positions": [-1.35, 1.35], "tread_half_height": 7.328 / 16,
                   "excluded_reference_meshes": dict(excluded), "restored_brake_discs": sorted(restored), "parts": counts}
        result[SOURCE / (directory + "_parts.json")] = json_bytes(summary)
        print(directory + ": " + str(len(parts)) + " parts, " + str(sum(v["faces"] for v in counts.values())) + " faces")
        frame_texture = next(t for t in frame["textures"] if t["name"] == "crh1a_bogie_frame_motor.png")
        texture_bytes = base64.b64decode(frame_texture["source"].split(",", 1)[1])
        texture_path = TEXTURES / directory / "frame.png"
        result[texture_path] = texture_bytes
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate committed exports without changing files")
    args = parser.parse_args()
    files = outputs()
    mismatches = []
    for path, data in files.items():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                mismatches.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if mismatches:
        raise SystemExit("Stale or missing exports:\n" + "\n".join(mismatches))
    print(("Verified " if args.check else "Wrote ") + str(len(files)) + " files")


if __name__ == "__main__":
    main()
